  factory PlanState.fromMap(Map<String, dynamic> map) {
    final defaults = PlanState();
    double number(String key, double fallback) =>
        (map[key] as num?)?.toDouble() ?? fallback;
    List<List<dynamic>> rows(String key, List<List<dynamic>> fallback) {
      final value = map[key];
      if (value is! List) {
        return fallback.map((row) => List<dynamic>.from(row)).toList();
      }
      return value
          .whereType<List>()
          .map(
            (row) => row
                .map((cell) => cell is num ? cell.toDouble() : cell)
                .toList(),
          )
          .toList();
    }

    final rawUtil = map['util'];
    final rawSel = map['sel'];
